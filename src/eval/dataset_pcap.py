"""
Phase 2.5 — build the eval set from payload-derived pcap flows.

Emits the SAME LabeledAlert records as src/eval/dataset.py, so the existing
retrieval and answer-quality harnesses run against it unchanged. That makes the
comparison clean: identical metrics, identical ground truth, only the alert text
differs (flow statistics vs. payload-derived content).

LEAK DISCIPLINE (carried over):
  - IPs were already redacted during extraction; we re-assert it here.
  - _src_ip/_dst_ip and the _gt_* fields (attack name, CVE reference) are
    evaluation metadata ONLY and never enter alert_text.
  - Port numbers are included: a real analyst sees the port, and UNSW does not
    bind attack classes to fixed ports the way it binds them to IPs.

Usage:
    python -m src.eval.dataset_pcap --flows data/processed/flows_labeled.jsonl \
        --per-class 8 --out data/processed/eval_set_pcap.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
import re
from collections import defaultdict
from pathlib import Path

from src.eval.dataset import LabeledAlert, save_jsonl
from src.mapping import GROUND_TRUTH, get as get_mapping

_IP_RE = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")

_ALIASES = {
    "backdoors": "backdoor",
    "ddos": "ddos",
}


def normalize_class(raw: str) -> str:
    key = str(raw or "").strip().lower()
    return _ALIASES.get(key, key)


def render_flow_summary(rec: dict) -> str:
    """Terse flow line — the same style as the CSV-based renderer."""
    proto = str(rec.get("proto", "?")).upper()
    dport = rec.get("dst_port")
    pf, pb = rec.get("n_pkts_fwd", 0), rec.get("n_pkts_bwd", 0)
    bf, bb = rec.get("n_bytes_fwd", 0), rec.get("n_bytes_bwd", 0)
    dur = max(0.0, float(rec.get("last_ts", 0)) - float(rec.get("first_ts", 0)))

    head = f"{proto} flow to port {dport}"
    parts = [
        f"duration {dur:.2f}s",
        f"{pf} src pkts / {pb} dst pkts",
        f"{bf} src payload bytes / {bb} dst payload bytes",
    ]
    if pb == 0 and pf > 0:
        parts.append("no response from destination")
    return head + ". " + ", ".join(parts) + "."


_LIFT = {
    "long run of repeated no-operation bytes, buffer padding pattern":
        "long no-operation instruction sled and oversized padding, a memory-corruption "
        "and buffer overflow pattern used to hijack control flow",
    "raw byte sequences corresponding to system call instructions":
        "embedded executable machine code invoking system calls, indicating attempted "
        "arbitrary code execution on the target",
    "repeated format specifier sequences in payload":
        "format string specifiers that can leak or overwrite memory, exploiting a "
        "software vulnerability in the remote service",
    "operating system shell command strings present in payload":
        "operating system command interpreter and shell invocation strings, indicating "
        "remote command execution",
    "SQL keywords and boolean tautology present in request parameters":
        "SQL injection payload targeting a public-facing web application database",
    "directory traversal sequences in requested path":
        "path traversal attempting unauthorized access to files outside the web root",
    "inline script markup embedded in request content":
        "injected client-side script targeting a web application user session",
    "payload is non-printable binary content":
        "opaque binary protocol payload with no readable content",
}


def lift_descriptor(d: str) -> str:
    """Raise a mechanical byte description to analyst-level phrasing.

    The first pass wrote deliberately mechanical text ("raw byte sequences
    corresponding to system call instructions"). Honest, but a different level
    of abstraction from ATT&CK, which describes adversary intent ("adversaries
    may exploit software vulnerabilities to execute code") — so the two don't
    land near each other in embedding space and retrieval missed.

    This still describes WHAT WAS OBSERVED, never the dataset's class label:
    "memory corruption pattern" describes the bytes; "Shellcode" would be the
    answer key.
    """
    for key, richer in _LIFT.items():
        if d.startswith(key):
            return richer
    return d


_LOW_CONFIDENCE_PREFIXES = (
    "payload contains readable content",
    "payload is non-printable binary content",
    "opaque binary protocol payload",
    "requested host header",
    "client user-agent",
)


def is_confident(d: str) -> bool:
    """Keep only descriptors derived from signature matches or protocol parsing.

    UNSW traffic was generated by IXIA PerfectStorm, and for most classes the
    payloads are randomized filler rather than real attack content. The generic
    "readable content: <junk>" fallback therefore injects random tokens that
    dominate the embedding and push it away from every technique — measured as
    worse than including no payload text at all.
    """
    return not d.startswith(_LOW_CONFIDENCE_PREFIXES)


def render_alert(rec: dict, include_payload: bool = True, payload_first: bool = True) -> str:
    """Flow summary plus HIGH-CONFIDENCE payload descriptors only."""
    flow = render_flow_summary(rec)
    if not include_payload:
        return _IP_RE.sub("<ip>", flow)

    descriptors = [lift_descriptor(d) for d in (rec.get("payload_text") or [])
                   if d and is_confident(d)]
    if not descriptors:
        return _IP_RE.sub("<ip>", flow)

    content = "Observed content: " + "; ".join(descriptors[:4]) + "."
    text = f"{content} {flow}" if payload_first else f"{flow} {content}"
    return _IP_RE.sub("<ip>", text)


def build_eval_set(
    flows_path: str,
    per_class: int = 8,
    seed: int = 13,
    include_payload: bool = True,
    normal_cap: int | None = None,
) -> list[LabeledAlert]:
    by_class: dict[str, list[dict]] = defaultdict(list)
    with open(flows_path) as f:
        for line in f:
            if not line.strip():
                continue
            rec = json.loads(line)
            cls = normalize_class(rec.get("attack_class"))
            by_class[cls].append(rec)

    unknown = sorted(set(by_class) - set(GROUND_TRUTH))
    if unknown:
        print(f"[dataset-pcap] WARNING — classes with no mapping entry, skipped: {unknown}")

    rng = random.Random(seed)
    alerts: list[LabeledAlert] = []
    short: list[str] = []
    for cls in sorted(set(by_class) & set(GROUND_TRUTH)):
        rows = by_class[cls]
        rng.shuffle(rows)
        take = per_class if (cls != "normal" or normal_cap is None) else normal_cap
        picked = rows[:take]
        if len(picked) < take:
            short.append(f"{cls} ({len(picked)}/{take})")
        entry = get_mapping(cls)
        for j, rec in enumerate(picked):
            alerts.append(LabeledAlert(
                alert_id=f"{cls}-{j:03d}",
                alert_text=render_alert(rec, include_payload=include_payload),
                attack_class=cls,
                true_severity=entry.severity,
                true_technique_ids=entry.technique_ids,
            ))
    if short:
        print(f"[dataset-pcap] NOTE — under-filled classes: {', '.join(short)}")
    missing = sorted(set(GROUND_TRUTH) - set(by_class) - {"ddos", "injection", "mitm",
                                                          "password", "ransomware",
                                                          "scanning", "xss"})
    if missing:
        print(f"[dataset-pcap] NOTE — UNSW classes absent from this capture: {missing}")

    rng.shuffle(alerts)
    return alerts


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--flows", default="data/processed/flows_labeled.jsonl")
    ap.add_argument("--per-class", type=int, default=8)
    ap.add_argument("--seed", type=int, default=13)
    ap.add_argument("--out", default="data/processed/eval_set_pcap.jsonl")
    ap.add_argument("--no-payload", action="store_true",
                    help="ablation: flow stats only, no payload descriptors")
    args = ap.parse_args()

    alerts = build_eval_set(args.flows, per_class=args.per_class, seed=args.seed,
                            include_payload=not args.no_payload)
    print(f"[dataset-pcap] built {len(alerts)} alerts across "
          f"{len(set(a.attack_class for a in alerts))} classes")
    print("\n--- sample alerts ---")
    seen = set()
    for a in alerts:
        if a.attack_class in seen:
            continue
        seen.add(a.attack_class)
        print(f"\n[{a.attack_class}] sev={a.true_severity.value} {a.true_technique_ids}")
        print(f"  {a.alert_text[:300]}")
        if len(seen) >= 5:
            break
    save_jsonl(alerts, args.out)